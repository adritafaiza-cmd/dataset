module cdc_2phase_clearable #(
  parameter WIDTH = 1,
  parameter SYNC_STAGES = 3,
  parameter CLEAR_ON_ASYNC_RESET = 1
)(
  input  src_rst_ni,
  input  src_clk_i,
  input  src_clear_i,
  output src_clear_pending_o,
  input  [WIDTH-1:0] src_data_i,
  input  src_valid_i,
  output src_ready_o,
  input  dst_rst_ni,
  input  dst_clk_i,
  input  dst_clear_i,
  output dst_clear_pending_o,
  output [WIDTH-1:0] dst_data_o,
  output dst_valid_o,
  input  dst_ready_i
);

  // ------------------------------------------------------------------
  // 1. Clock Domain Crossing: Source Signals to Destination Domain
  // ------------------------------------------------------------------
  // We need to capture src_valid, src_ready, src_clear_i, and src_data_i
  // in the destination clock domain.
  // Since src_ready is an output of this module, we cannot capture it directly
  // from the input port. Instead, we capture the handshake state internally
  // or use a separate CDC path for the handshake signal if we were designing
  // a full FIFO. However, for a simple 2-phase channel, the standard approach
  // is to capture the incoming control signals (valid, clear) and the data.
  // The 'ready' signal is generated by the destination logic based on its own state.
  
  // Capture src_valid and src_clear_i
  logic [SYNC_STAGES-1:0] src_valid_sync;
  logic [SYNC_STAGES-1:0] src_clear_sync;
  logic [SYNC_STAGES-1:0] src_data_sync;
  
  // Capture dst_ready_i for the source side (handled in the next block)
  // But first, let's define the destination side logic which drives dst_valid_o
  // and consumes the synced signals.

  // ------------------------------------------------------------------
  // 2. Destination Side Logic (dst_clk_i domain)
  // ------------------------------------------------------------------
  // State Machine for Destination
  // States: IDLE, WAITING_FOR_DATA, WAITING_FOR_ACK
  
  typedef enum logic [1:0] {
    DST_IDLE,
    DST_WAITING_DATA,
    DST_WAITING_ACK
  } dst_state_t;

  dst_state_t dst_state, dst_state_next;
  logic [WIDTH-1:0] dst_data_reg;
  logic dst_valid_reg;
  logic dst_clear_pending_reg;
  
  // Handshake signals for the clear mechanism
  // The problem states: "Each clear step reaches the other clock one handshake later."
  // This implies a specific protocol for clearing.
  // Protocol interpretation:
  // 1. Source sends Clear Request.
  // 2. Destination acknowledges Clear Request (implicitly by stopping and resetting).
  // 3. Destination sends Clear Acknowledge (or Source waits for it).
  // The prompt says: "drops the one outstanding beat by returning request and acknowledge to zero."
  // This suggests the channel holds one beat during clear.
  
  // Let's implement a specific Clear Protocol:
  // - Source asserts src_clear_i.
  // - Destination must see this, stop sending valid, and reset its internal state.
  // - Destination asserts dst_clear_pending_o to tell Source it is clearing.
  // - Source waits for dst_clear_pending_o, then de-asserts src_clear_i.
  // - Destination sees de-assertion of src_clear_i (via CDC), asserts dst_valid=0, dst_ready=1 (if needed), 
  //   and resets internal data.
  // - To satisfy "one handshake later", we might need an explicit handshake signal between clear steps.
  // However, the prompt says "returning request and acknowledge to zero". 
  // Let's interpret this as:
  // Source: Assert Clear -> Wait for Ack -> De-assert Clear.
  // Dest: See Clear -> Assert Pending -> Wait for De-assert -> Reset.
  
  // CDC for dst_ready_i to src domain
  logic [SYNC_STAGES-1:0] dst_ready_sync;
  
  // CDC for src_clear_i to dst domain (already defined above as src_clear_sync)
  
  // CDC for dst_clear_pending_o to src domain
  logic [SYNC_STAGES-1:0] dst_clear_pending_sync;

  // ------------------------------------------------------------------
  // 3. Source Side Logic (src_clk_i domain)
  // ------------------------------------------------------------------
  // Capture dst_ready and dst_clear_pending
  always_ff @(posedge src_clk_i or negedge src_rst_ni) begin
    if (!src_rst_ni) begin
      dst_ready_sync <= '{default: 0};
      dst_clear_pending_sync <= '{default: 0};
    end else begin
      dst_ready_sync <= dst_ready_sync[SYNC_STAGES-1:1] | {dst_ready_i, dst_ready_sync[SYNC_STAGES-2:0]};
      dst_clear_pending_sync <= dst_clear_pending_sync[SYNC_STAGES-1:1] | {dst_clear_pending_i, dst_clear_pending_sync[SYNC_STAGES-2:0]};
    end
  end

  // Capture src_valid, src_clear_i, src_data_i for destination
  always_ff @(posedge src_clk_i or negedge src_rst_ni) begin
    if (!src_rst_ni) begin
      src_valid_sync <= '{default: 0};
      src_clear_sync <= '{default: 0};
      src_data_sync <= '{default: 0};
    end else begin
      src_valid_sync <= src_valid_sync[SYNC_STAGES-1:1] | {src_valid_i, src_valid_sync[SYNC_STAGES-2:0]};
      src_clear_sync <= src_clear_sync[SYNC_STAGES-1:1] | {src_clear_i, src_clear_sync[SYNC_STAGES-2:0]};
      src_data_sync <= src_data_sync[SYNC_STAGES-1:1] | {src_data_i, src_data_sync[SYNC_STAGES-2:0]};
    end
  end

  // ------------------------------------------------------------------
  // 4. Destination State Machine
  // ------------------------------------------------------------------
  always_ff @(posedge dst_clk_i or negedge dst_rst_ni) begin
    if (!dst_rst_ni) begin
      dst_state <= DST_IDLE;
      dst_data_reg <= '{default: 0};
      dst_valid_reg <= 1'b0;
      dst_clear_pending_reg <= 1'b0;
    end else begin
      dst_state <= dst_state_next;
      dst_data_reg <= dst_data_reg;
      dst_valid_reg <= dst_valid_reg;
      dst_clear_pending_reg <= dst_clear_pending_reg;
    end
  end

  // Next State Logic
  always_comb begin
    dst_state_next = dst_state;
    dst_data_reg = dst_data_reg;
    dst_valid_reg = 1'b0;
    dst_clear_pending_reg = 1'b0;
    
    // Default outputs
    dst_data_o = dst_data_reg;
    dst_valid_o = dst_valid_reg;
    dst_ready_o = 1'b1; // Default ready, unless busy

    case (dst_state)
      DST_IDLE: begin
        // Wait for valid data
        if (src_valid_sync[SYNC_STAGES-1]) begin
          dst_state_next = DST_WAITING_DATA;
          dst_data_reg = src_data_sync[SYNC_STAGES-1];
          dst_valid_reg = 1'b1;
          dst_ready_o = 1'b0; // Busy sending
        end
      end

      DST_WAITING_DATA: begin
        // Hold data, wait for ready
        if (dst_ready_i) begin
          dst_state_next = DST_WAITING_ACK;
          // Data is already latched in dst_data_reg
          // We need to signal that we are done with this beat so source can send next or clear
          // But the protocol requires a clear handshake.
          // Let's assume standard handshake for data, then special handling for clear.
          // Actually, the prompt says "holding it while the receiver waits".
          // So we stay in WAITING_DATA until dst_ready_i is high.
          // Once dst_ready_i is high, we move to WAITING_ACK to allow source to send next or clear.
          // But wait, if we move to WAITING_ACK immediately, we might lose the "hold" if the source 
          // doesn't send next immediately. 
          // Standard 2-phase: 
          // 1. Src Valid -> Dest captures data, sets Valid=1, Ready=0.
          // 2. Dest Ready=1 (after receiving ack from src? No, standard is Src Valid & Dest Ready).
          // Let's refine the state machine for standard 2-phase first, then integrate clear.
          
          // Revised Logic for Data Transfer:
          // State 1: Idle. Wait for Src Valid.
          // State 2: Data Captured. Set Valid=1, Ready=0. Wait for Src Ready (which is implicit if we don't block).
          // Actually, the standard handshake is:
          // Src: Valid=1, Ready=?.
          // Dest: Valid=?, Ready=1.
          // When Src Valid=1 and Dest Ready=1, transfer happens.
          // Then Src Valid=0, Dest Valid=1.
          // Then Dest Ready=0 (if it needs to process), Src Ready=1.
          // Then Dest Valid=0, Dest Ready=1.
          
          // Given the "holding it while receiver waits" requirement:
          // If Dest is busy (processing), it sets Ready=0. Src must wait (Valid=0).
          // So:
          // 1. Src Valid=1. Dest captures data. Dest sets Valid=1, Ready=0.
          // 2. Src sees Ready=0, sets Valid=0.
          // 3. Dest processes data. Dest sets Valid=0, Ready=1.
          // 4. Src sees Ready=1, sets Valid=1 for next data.
          
          // Let's implement this flow.
          if (dst_ready_i) begin
             // This block is entered when we are waiting for the handshake to complete?
             // No, let's simplify.
             // State: IDLE.
             // If src_valid_sync: 
             //    Capture data.
             //    Set dst_valid_o = 1.
             //    Set dst_ready_o = 0.
             //    Next State = WAITING_HANDSHAKE.
             // State: WAITING_HANDSHAKE.
             //    Wait for src_ready (which is implicit if we assume src_valid goes low when ready is low).
             //    Actually, we don't capture src_ready. We assume the handshake is done when src_valid goes low.
             //    But we need to know when src_valid goes low to release the ready signal.
             //    We can track if src_valid was high in the previous cycle.
             
             // Let's use a simpler state machine that tracks the handshake phase.
             // Phase 1: Waiting for Src Valid.
             // Phase 2: Data Sent (Valid=1, Ready=0).
             // Phase 3: Waiting for Src to release Valid (i.e., Src Ready).
             // Phase 4: Data Received (Valid=0, Ready=1).
             
             // To implement Phase 3, we need to know if src_valid was high.
             // We can use the sync register.
             
             // Let's restart the state logic with a clearer flow.
          end
        end
      end
    endcase
  end

  // ------------------------------------------------------------------
  // 5. Refined Destination Logic with Handshake and Clear
  // ------------------------------------------------------------------
  // We will use a finite state machine that explicitly handles the handshake phases.
  
  // Signals for tracking handshake progress
  logic src_valid_prev; // Captured in dst domain
  logic dst_valid_prev; // Captured in src domain (for src side logic)
  
  // CDC for src_valid to track when it goes low
  always_ff @(posedge dst_clk_i or negedge dst_rst_ni) begin
    if (!dst_rst_ni) begin
      src_valid_prev <= 1'b0;
    end else begin
      src_valid_prev <= src_valid_sync[SYNC_STAGES-1];
    end
  end

  // CDC for dst_valid to src domain (needed for src to know when data is consumed)
  // Wait, src_ready_o is an output. Src needs to know if dst is ready.
  // Src_ready_o is driven by the source logic based on dst_ready_sync.
  // But for the handshake completion, Src needs to know when dst_valid goes low.
  // Actually, standard handshake:
  // Src: Valid=1, Ready=1.
  // Dest: Valid=0, Ready=1.
  // Src: Valid=1, Ready=0 (if busy).
  // Dest: Valid=1, Ready=0.
  // Src: Valid=0, Ready=1.
  // Dest: Valid=0, Ready=1.
  
  // The "holding" requirement means if Dest is busy, it sets Ready=0.
  // So Src must wait (Valid=0).
  
  // Let's define the states properly:
  // IDLE: Waiting for src_valid.
  // CAPTURE: src_valid is high. Capture data. Set dst_valid=1, dst_ready=0.
  // WAIT_SRC_RELEASE: Wait for src_valid to go low (meaning src is ready).
  // RELEASE: src_valid is low. Set dst_valid=0, dst_ready=1.
  
  // Clear Logic Integration:
  // If src_clear_sync is high:
  //   Force state to CLEAR_WAIT_ACK.
  //   Set dst_clear_pending_o = 1.
  //   Stop normal data flow.
  // If src_clear_sync goes low (and we are in CLEAR_WAIT_ACK):
  //   Reset state to IDLE.
  //   Reset dst_data_reg.
  //   Set dst_valid=0, dst_ready=1.
  //   Set dst_clear_pending_o = 0.
  
  // Note: "Each clear step reaches the other clock one handshake later."
  // This implies:
  // 1. Src asserts Clear.
  // 2. Dest sees Clear, asserts Clear_Pending.
  // 3. Src sees Clear_Pending, de-asserts Clear.
  // 4. Dest sees Clear de-asserted, resets.
  // This is exactly the flow described above.

  // CDC for dst_valid to src domain (for src_ready logic)
  logic [SYNC_STAGES-1:0] dst_valid_sync_src;
  always_ff @(posedge src_clk_i or negedge src_rst_ni) begin
    if (!src_rst_ni) begin
      dst_valid_sync_src <= '{default: 0};
    end else begin
      dst_valid_sync_src <= dst_valid_sync_src[SYNC_STAGES-1:1] | {dst_valid_o, dst_valid_sync_src[SYNC_STAGES-2:0]};
    end
  end

  // ------------------------------------------------------------------
  // 6. Destination State Machine Implementation
  // ------------------------------------------------------------------
  typedef enum logic [2:0] {
    DST_IDLE,
    DST_CAPTURE,
    DST_WAIT_SRC_RELEASE,
    DST_RELEASE,
    DST_CLEAR_WAIT_ACK,
    DST_CLEAR_DONE
  } dst_fsm_t;

  dst_fsm_t dst_fsm, dst_fsm_next;
  
  always_ff @(posedge dst_clk_i or negedge dst_rst_ni) begin
    if (!dst_rst_ni) begin
      dst_fsm <= DST_IDLE;
      dst_data_reg <= '{default: 0};
      dst_valid_reg <= 1'b0;
      dst_clear_pending_reg <= 1'b0;
    end else begin
      dst_fsm <= dst_fsm_next;
      dst_data_reg <= dst_data_reg;
      dst_valid_reg <= dst_valid_reg;
      dst_clear_pending_reg <= dst_clear_pending_reg;
    end
  end

  always_comb begin
    dst_fsm_next = dst_fsm;
    dst_data_reg = dst_data_reg;
    dst_valid_reg = 1'b0;
    dst_ready_o = 1'b1;
    dst_clear_pending_o = 1'b0;
    
    case (dst_fsm)
      DST_IDLE: begin
        if (src_valid_sync[SYNC_STAGES-1]) begin
          dst_fsm_next = DST_CAPTURE;
          dst_data_reg = src_data_sync[SYNC_STAGES-1];
          dst_valid_reg = 1'b1;
          dst_ready_o = 1'b0;
        end
        // Check for clear request
        if (src_clear_sync[SYNC_STAGES-1]) begin
          dst_fsm_next = DST_CLEAR_WAIT_ACK;
          dst_clear_pending_o = 1'b1;
          // Do not capture data during clear
        end
      end

      DST_CAPTURE: begin
        // Hold data, wait for src to release valid (i.e., src ready)
        // We check if src_valid went low in the previous cycle (src_valid_prev)
        if (src_valid_prev) begin
          // Still waiting for src to release
        end else begin
          // src_valid is low, handshake complete
          dst_fsm_next = DST_RELEASE;
          dst_valid_reg = 1'b0;
          dst_ready_o = 1'b1;
        end
        // Check for clear request while capturing? 
        // Usually clear takes precedence. If clear comes while capturing, abort.
        if (src_clear_sync[SYNC_STAGES-1]) begin
          dst_fsm_next = DST_CLEAR_WAIT_ACK;
          dst_clear_pending_o = 1'b1;
          dst_valid_reg = 1'b0; // Stop driving valid
          dst_ready_o = 1'b1; // Allow src to proceed with clear
        end
      end

      DST_WAIT_SRC_RELEASE: begin
        // This state is effectively the same as DST_CAPTURE but we already captured.
        // Wait for src_valid to go low.
        if (src_valid_prev) begin
          // Still waiting
        end else begin
          dst_fsm_next = DST_RELEASE;
          dst_valid_reg = 1'b0;
          dst_ready_o = 1'b1;
        end
        if (src_clear_sync[SYNC_STAGES-1]) begin
          dst_fsm_next = DST_CLEAR_WAIT_ACK;
          dst_clear_pending_o = 1'b1;
          dst_valid_reg = 1'b0;
          dst_ready_o = 1'b1;
        end
      end

      DST_RELEASE: begin
        // Data consumed. Ready for next.
        dst_fsm_next = DST_IDLE;
        dst_valid_reg = 1'b0;
        dst_ready_o = 1'b1;
        if (src_clear_sync[SYNC_STAGES-1]) begin
          dst_fsm_next = DST_CLEAR_WAIT_ACK;
          dst_clear_pending_o = 1'b1;
        end
      end

      DST_CLEAR_WAIT_ACK: begin
        // Waiting for src to de-assert clear.
        // We need to detect the transition of src_clear_sync from 1 to 0.
        // We can use a register to track if it was high.
        // Let's add a register for src_clear_prev in dst domain.
        // But for simplicity in this block, we assume the logic below handles it.
        // Actually, we need to know if it was high in the previous cycle.
        // Let's add a local variable or register for this.
        // Since we can't easily add variables outside the always block without cluttering,
        // let's use a register inside the module.
        
        // For now, let's assume we handle the transition in the next block or use a register.
        // Let's add a register for src_clear_prev_dst.
      end
      
      DST_CLEAR_DONE: begin
        dst_fsm_next = DST_IDLE;
        dst_data_reg = '{default: 0};
        dst_valid_reg = 1'b0;
        dst_clear_pending_o = 1'b0;
        dst_ready_o = 1'b1;
      end
    endcase
  end

  // ------------------------------------------------------------------
  // 7. Source Side Logic
  // ------------------------------------------------------------------
  // Drive src_ready_o based on dst_ready_sync
  // Drive src_clear_pending_o based on dst_clear_pending_sync
  
  always_ff @(posedge src_clk_i or negedge src_rst_ni) begin
    if (!src_rst_ni) begin
      src_ready_o <= 1'b1;
      src_clear_pending_o <= 1'b0;
    end else begin
      src_ready_o <= dst_ready_sync[SYNC_STAGES-1];
      src_clear_pending_o <= dst_clear_pending_sync[SYNC_STAGES-1];
    end
  end

  // ------------------------------------------------------------------
  // 8. Clear Handshake Logic (Destination Side)
  // ------------------------------------------------------------------
  // We need to detect the falling edge of src_clear_sync to transition from 
  // CLEAR_WAIT_ACK to CLEAR_DONE.
  
  logic src_clear_prev_dst;
  always_ff @(posedge dst_clk_i or negedge dst_rst_ni) begin
    if (!dst_rst_ni) begin
      src_clear_prev_dst <= 1'b0;
    end else begin
      src_clear_prev_dst <= src_clear_sync[SYNC_STAGES-1];
    end
  end

  always_comb begin
    // Override the FSM next state logic for the clear transition
    if (dst_fsm == DST_CLEAR_WAIT_ACK && src_clear_sync[SYNC_STAGES-1] == 1'b0 && src_clear_prev_dst == 1'b1) begin
      dst_fsm_next = DST_CLEAR_DONE;
    end
  end

  // ------------------------------------------------------------------
  // 9. Source Clear Logic
  // ------------------------------------------------------------------
  // The source should wait for dst_clear_pending_o to go high before de-asserting src_clear_i.
  // However, the prompt says "A clear isolates both ends, then drops the one outstanding beat...".
  // And "Each clear step reaches the other clock one handshake later."
  // This implies:
  // 1. Src asserts Clear.
  // 2. Dest sees Clear, asserts Clear_Pending.
  // 3. Src sees Clear_Pending, de-asserts Clear.
  // 4. Dest sees Clear de-asserted, resets.
  
  // The source logic for clearing is external to this module's internal state machine,
  // but the module must ensure it doesn't accept new data while clearing.
  // The FSM logic above handles the destination side of the clear handshake.
  // The source side behavior (waiting for pending) is assumed to be handled by the user
  // or by the fact that src_ready_o will be 0 while dst is clearing?
  // No, dst_ready_o is 1 during clear (to allow src to de-assert).
  // So the user must implement the handshake on the src side:
  // while (src_clear_pending_o) src_clear_i = 1;
  // else src_clear_i = 0;
  
  // However, the module itself must ensure that if src_clear_i is asserted, 
  // no new data is accepted. This is handled in the DST_IDLE state.
  
  // One detail: "drops the one outstanding beat".
  // If there was a beat in flight (DST_CAPTURE or DST_WAIT_SRC_RELEASE), 
  // the clear request should abort it.
  // Our logic in DST_CAPTURE and DST_WAIT_SRC_RELEASE checks for src_clear_sync and transitions to CLEAR_WAIT_ACK.
  // This effectively aborts the current beat.
  
  // Final check on "no extra valid gap between beats".
  // Standard 2-phase handshake ensures this naturally.
  // Src Valid -> Dest Valid -> Src Ready -> Dest Ready -> Src Valid (next).
  // No gaps.

endmodule
