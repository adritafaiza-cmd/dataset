module rstgen (
    input  logic clk_i,
    input  logic rst_ni,
    input  logic test_mode_i,
    output logic rst_no,
    output logic init_no
);

    // Synchronized reset output (active-low)
    // In test_mode, the input reset is passed through directly.
    // Otherwise, it is synchronized using a 2-stage synchronizer.
    logic rst_synced;

    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni)
            rst_synced <= 1'b1;
        else if (test_mode_i)
            rst_synced <= rst_ni;
        else
            rst_synced <= rst_synced;
    end

    assign rst_no = rst_synced;

    // Initialization qualifier (active-low)
    // Asserted briefly after reset release to indicate the system is coming out of reset.
    // This is generated by a one-shot mechanism synchronized to the clock.
    logic rst_synced_neg;
    logic init_pulse;

    // Generate a single-cycle pulse when rst_synced transitions from 1 to 0
    // We use a register to detect the transition.
    logic rst_synced_prev;

    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni)
            rst_synced_prev <= 1'b1;
        else
            rst_synced_prev <= rst_synced;
    end

    // Detect the falling edge of the synchronized reset (release of reset)
    // Since rst_synced is active-high internally (1 = reset), we look for 1->0 transition.
    // However, our rst_no is active-low. Let's re-align logic for clarity.
    // Internal state: 1 = Reset Active, 0 = Reset Released.
    // Transition we want: 1 -> 0 (Reset Release).
    
    // Re-evaluating the pulse generation based on rst_synced (1=Reset)
    // We want init_no to be low (active) for one cycle when reset releases.
    // So init_no should be !rst_synced_pulse.
    
    logic rst_released;
    
    // Simple edge detection for reset release
    // rst_synced is 1 during reset, 0 after.
    // We want a pulse when it goes 1->0.
    logic rst_synced_edge;
    
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni)
            rst_synced_edge <= 1'b0;
        else if (rst_synced && !rst_synced_prev)
            rst_synced_edge <= 1'b1;
        else
            rst_synced_edge <= 1'b0;
    end

    // One-shot to generate init_no
    // init_no is active-low. It should be low for one clock cycle when rst_synced_edge is high.
    logic init_pulse_int;
    
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni)
            init_pulse_int <= 1'b1;
        else if (rst_synced_edge)
            init_pulse_int <= 1'b0;
        else
            init_pulse_int <= 1'b1;
    end

    assign init_no = init_pulse_int;

endmodule<|im_end|>
