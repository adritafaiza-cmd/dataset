module async_fifo
    #(
        parameter DSIZE = 8,
        parameter ASIZE = 4,
        parameter FALLTHROUGH = "TRUE"
    )(
        input  wire             wclk,
        input  wire             wrst_n,
        input  wire             winc,
        input  wire [DSIZE-1:0] wdata,
        output wire             wfull,
        output wire             awfull,
        input  wire             rclk,
        input  wire             rrst_n,
        input  wire             rinc,
        output wire [DSIZE-1:0] rdata,
        output wire             rempty,
        output wire             arempty
    );

    localparam FSIZE = 2**ASIZE;

    reg [DSIZE-1:0] mem [FSIZE-1:0];
    reg [ASIZE-1:0] wptr;
    reg [ASIZE-1:0] rptr;
    reg [ASIZE:0]   wcnt;
    reg [ASIZE:0]   rcnt;

    assign wfull = (wcnt == FSIZE);
    assign awfull = (wcnt == FSIZE-1);
    assign rempty = (rcnt == 0);
    assign arempty = (rcnt == 1);

    always @(posedge wclk or negedge wrst_n) begin
        if (~wrst_n) begin
            wptr <= 0;
            wcnt <= 0;
        end else if (winc && ~wfull) begin
            mem[wptr] <= wdata;
            wptr <= wptr + 1;
            wcnt <= wcnt + 1;
        end
    end

    always @(posedge rclk or negedge rrst_n) begin
        if (~rrst_n) begin
            rptr <= 0;
            rcnt <= 0;
        end else if (rinc && ~rempty) begin
            rdata <= mem[rptr];
            rptr <= rptr + 1;
            rcnt <= rcnt - 1;
        end
    end

    always @(posedge wclk or negedge wrst_n) begin
        if (~wrst_n) begin
            wcnt <= 0;
        end else if (winc && ~wfull) begin
            wcnt <= wcnt + 1;
        end else if (~winc && ~wfull) begin
            wcnt <= wcnt - 1;
        end
    end

    always @(posedge rclk or negedge rrst_n) begin
        if (~rrst_n) begin
            rcnt <= 0;
        end else if (rinc && ~rempty) begin
            rcnt <= rcnt - 1;
        end else if (~rinc && ~rempty) begin
            rcnt <= rcnt + 1;
        end
    end

