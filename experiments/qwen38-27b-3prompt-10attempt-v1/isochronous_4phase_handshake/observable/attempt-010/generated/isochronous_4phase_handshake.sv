module isochronous_4phase_handshake (
    input  src_clk_i,
    input  src_rst_ni,
    input  src_valid_i,
    output src_ready_o,
    input  dst_clk_i,
    input  dst_rst_ni,
    output dst_valid_o,
    input  dst_ready_i
);

    // Synchronizer for src_valid_i into dst domain
    reg [1:0] src_valid_sync;
    always @(posedge dst_clk_i or negedge dst_rst_ni) begin
        if (!dst_rst_ni)
            src_valid_sync <= 2'b00;
        else
            src_valid_sync <= {src_valid_sync[0], src_valid_i};
    end
    wire src_valid_dst = src_valid_sync[1];

    // Synchronizer for dst_ready_i into src domain
    reg [1:0] dst_ready_sync;
    always @(posedge src_clk_i or negedge src_rst_ni) begin
        if (!src_rst_ni)
            dst_ready_sync <= 2'b00;
        else
            dst_ready_sync <= {dst_ready_sync[0], dst_ready_i};
    end
    wire dst_ready_src = dst_ready_sync[1];

    // Synchronizer for src_ready_o into dst domain
    reg [1:0] src_ready_sync;
    always @(posedge dst_clk_i or negedge dst_rst_ni) begin
        if (!dst_rst_ni)
            src_ready_sync <= 2'b00;
        else
            src_ready_sync <= {src_ready_sync[0], src_ready_o};
    end
    wire src_ready_dst = src_ready_sync[1];

    // Synchronizer for dst_valid_o into src domain
    reg [1:0] dst_valid_sync;
    always @(posedge src_clk_i or negedge src_rst_ni) begin
        if (!src_rst_ni)
            dst_valid_sync <= 2'b00;
        else
            dst_valid_sync <= {dst_valid_sync[0], dst_valid_o};
    end
    wire dst_valid_src = dst_valid_sync[1];

    // Source side: generate src_ready_o
    // src_ready_o should be high when the source is ready to accept a new transfer.
    // In a four-phase handshake, the source asserts valid, waits for ready, then deasserts valid.
    // The source is ready when it is not in the middle of a transfer.
    // We track the state of the source side.
    
    // Let's think about the four-phase handshake protocol:
    // Phase 1: src_valid_i = 0, src_ready_o = 0 (idle)
    // Phase 2: src_valid_i = 1, src_ready_o = 0 (source asserts valid)
    // Phase 3: src_valid_i = 1, src_ready_o = 1 (destination asserts ready)
    // Phase 4: src_valid_i = 0, src_ready_o = 1 (source deasserts valid)
    // Then back to Phase 1: src_valid_i = 0, src_ready_o = 0
    
    // The source controls src_valid_i (input to this module) and src_ready_o (output).
    // Wait, src_valid_i is an input, meaning the source side (outside this module) drives it.
    // And src_ready_o is an output, meaning this module drives it back to the source.
    // Similarly, dst_valid_o is an output (this module drives it to destination), and dst_ready_i is an input (destination drives it back).
    
    // So this module is the "bridge" between source and destination.
    // The source drives src_valid_i and receives src_ready_o.
    // The destination drives dst_ready_i and receives dst_valid_o.
    
    // For the four-phase handshake:
    // Source side: source asserts src_valid_i, waits for src_ready_o to go high, then deasserts src_valid_i.
    // Destination side: destination sees dst_valid_o, asserts dst_ready_i, waits for dst_valid_o to go low, then deasserts dst_ready_i.
    
    // This module needs to:
    // 1. When src_valid_i is asserted (and synchronized to dst domain), assert dst_valid_o.
    // 2. When dst_ready_i is asserted (and synchronized to src domain), assert src_ready_o.
    // 3. When src_ready_o is high and src_valid_i is high, the transfer is complete. The source will deassert src_valid_i.
    // 4. When dst_valid_o is low and dst_ready_i is high, the destination will deassert dst_ready_i.
    
    // Let's use a state machine in each domain.
    
    // Source domain state machine for src_ready_o
    // States: IDLE (ready=0), WAIT_VALID (ready=0, waiting for valid), WAIT_DEASSERT (ready=1, waiting for valid to deassert)
    // Actually, let's think more carefully.
    
    // src_ready_o should be:
    // - 0 when no transfer is in progress and we're not expecting a valid
    // - 0 when valid is asserted but we haven't confirmed the transfer yet
    // - 1 when the transfer is confirmed (dst has accepted) and we're waiting for valid to deassert
    // - 0 when valid has deasserted (back to idle)
    
    // Let's use a simple approach:
    // src_ready_o = dst_ready_src (synchronized)
    // But we need to ensure that src_ready_o only goes high when a valid transfer is being completed.
    
    // Actually, in a four-phase handshake, the ready signal is generated by the receiver.
    // The source asserts valid, the destination asserts ready when it's ready to accept.
    // When both valid and ready are high, the transfer occurs.
    // Then valid deasserts, then ready deasserts.
    
    // So:
    // src_ready_o should be high when the destination is ready to accept a transfer.
    // dst_valid_o should be high when the source has a valid transfer.
    
    // Let's define:
    // dst_valid_o = src_valid_dst (synchronized src_valid_i)
    // src_ready_o = dst_ready_src (synchronized dst_ready_i)
    
    // But we need to be careful about the four-phase protocol. The ready should only be asserted when there's a valid, or the valid should only be asserted when there's a ready? No, in four-phase, they can be independent.
    
    // Let's just do:
    assign dst_valid_o = src_valid_dst;
    assign src_ready_o = dst_ready_src;

endmodule
